function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const location = useLocation();

  console.log(
    "🔥 ROOT LOCATION:",
    location.pathname,
  );

  const publicRoutes = [
    "/bem-vindo",
    "/login",
    "/signup",
    "/forgot-password",
    "/reset-password",
  ];




const isPublicRoute = publicRoutes.includes(location.pathname);

  return (
   <QueryClientProvider client={queryClient}>
  <RealtimeProvider>
    <AuthProvider>
     

      {isPublicRoute ? (
        <Outlet />
      ) : (
        <AppShell>
          <Outlet />
        </AppShell>
      )}

      <Toaster />
    </AuthProvider>
  </RealtimeProvider>
</QueryClientProvider>
  );
}
